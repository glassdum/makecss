#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_7_rows_of_5() {
        for c in "AaBbZz0189 .,!?:-'()".chars() {
            let art = glyph_art(c);
            assert_eq!(art.len(), GLYPH_H);
            for row in art.iter() {
                assert_eq!(row.chars().count(), GLYPH_W, "글자 {c:?}의 한 줄 길이가 5가 아님");
            }
        }
    }

    #[test]
    fn scale_grows_with_font_size() {
        assert_eq!(scale_for(7.0), 1);
        assert_eq!(scale_for(16.0), 2);
        assert_eq!(scale_for(28.0), 4);
    }

    #[test]
    fn rasterizes_filled_pixels() {
        // 'I'는 가운데 세로줄이 있으니 진하기 255 픽셀이 존재해야 함.
        let gb = BitmapFont.rasterize('I', 14.0);
        assert!(gb.coverage.iter().any(|&c| c == 255));
        assert_eq!(gb.width, GLYPH_W * scale_for(14.0));
    }
}
