//! 아주 작은 5x7 비트맵 폰트 — 글자 모양을 손으로 직접 그렸습니다.
//!
//! 글자 하나는 5칸 x 7칸 모눈종이입니다. '#'은 '칠하는 픽셀', ' '은 '빈 픽셀'.
//! 그래서 아래 데이터를 그냥 눈으로 읽으면 글자 모양이 그대로 보입니다.
//!
//! 비유: 옛날 전광판/도트 프린터. 점을 켜고 끄는 패턴이 곧 글자입니다.
//! (진짜 .ttf 폰트는 글자를 '곡선 수식'으로 저장해 훨씬 복잡합니다 — 다음 단계 과제.)

/// 글자 한 칸의 너비(픽셀)와 높이(픽셀).
pub const GLYPH_W: usize = 5;
pub const GLYPH_H: usize = 7;

/// font-size(px)로부터 정수 확대 배율을 구합니다.
/// 원본 폰트는 7px 높이라, font-size 16 → 약 2배로 키워 그립니다(또렷하게 정수 배율).
pub fn scale_for(font_size: f32) -> usize {
    ((font_size / GLYPH_H as f32).round() as i32).max(1) as usize
}

/// 한 줄의 높이(픽셀) = 글자 높이 x 배율.
pub fn line_height(font_size: f32) -> f32 {
    (GLYPH_H * scale_for(font_size)) as f32
}

/// 글자 하나를 그린 뒤 다음 글자로 건너뛸 가로 거리 = (글자폭 + 1칸 간격) x 배율.
pub fn advance(font_size: f32) -> f32 {
    ((GLYPH_W + 1) * scale_for(font_size)) as f32
}

