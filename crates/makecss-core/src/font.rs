//! 손수 그린 5x7 비트맵 폰트와, 그것을 FontFace로 감싼 `BitmapFont`.
//!
//! 글자 하나는 5칸 x 7칸 모눈종이입니다. '#'은 '칠하는 픽셀', ' '은 '빈 픽셀'.
//! 아래 데이터를 눈으로 읽으면 글자 모양이 그대로 보입니다.
//!
//! 이 폰트는 외부 파일이 필요 없어 makecss의 '기본 폰트'입니다. 진짜 .ttf 폰트는
//! truetype.rs가 담당합니다(둘 다 같은 FontFace 약속을 지키므로 갈아끼울 수 있음).

use crate::fontface::{FontFace, GlyphBitmap};

/// 글자 한 칸의 너비/높이(원본 픽셀).
pub const GLYPH_W: usize = 5;
pub const GLYPH_H: usize = 7;

/// font-size(px)로부터 정수 확대 배율을 구합니다.
/// 원본이 7px 높이라, font-size 16 → 약 2배로 키워 또렷하게(정수 배율) 그립니다.
pub fn scale_for(font_size: f32) -> usize {
    ((font_size / GLYPH_H as f32).round() as i32).max(1) as usize
}

/// makecss의 기본 폰트. 상태가 없어 빈 구조체입니다.
pub struct BitmapFont;

impl FontFace for BitmapFont {
    fn ascent(&self, font_size: f32) -> f32 {
        // 기준선을 글자 칸의 '맨 아래'에 둡니다 → 글자 전체가 기준선 위에 있음.
        (GLYPH_H * scale_for(font_size)) as f32
    }

    fn line_height(&self, font_size: f32) -> f32 {
        // 글자 높이 + 1칸 줄 간격.
        ((GLYPH_H + 1) * scale_for(font_size)) as f32
    }

    fn advance(&self, _ch: char, font_size: f32) -> f32 {
        // 고정폭 폰트: 모든 글자가 같은 폭(글자폭 + 1칸 간격).
        ((GLYPH_W + 1) * scale_for(font_size)) as f32
    }

    fn rasterize(&self, ch: char, font_size: f32) -> GlyphBitmap {
        let scale = scale_for(font_size);
        let w = GLYPH_W * scale;
        let h = GLYPH_H * scale;
        let mut coverage = vec![0u8; w * h];

        let art = glyph_art(ch);
        for (row, line) in art.iter().enumerate() {
            for (col, cell) in line.chars().enumerate() {
                if cell != ' ' {
                    // 원본 한 칸을 scale x scale 블록으로 확대해 꽉(255) 칠합니다.
                    for dy in 0..scale {
                        for dx in 0..scale {
                            let px = col * scale + dx;
                            let py = row * scale + dy;
                            coverage[py * w + px] = 255;
                        }
                    }
                }
            }
        }

        GlyphBitmap {
            width: w,
            height: h,
            left: 0.0,
            top: h as f32, // 글자 전체가 기준선 위에 있으므로 top = 높이.
            coverage,
        }
    }
}

/// 글자 하나의 그림(7줄, 각 줄 5칸)을 돌려줍니다.
