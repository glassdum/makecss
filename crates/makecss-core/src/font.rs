#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_7_rows_of_5() {
        for c in "ABCXYZ0189 .,!?:-'()".chars() {
            let art = glyph_art(c);
            assert_eq!(art.len(), GLYPH_H);
            for row in art.iter() {
                assert_eq!(row.chars().count(), GLYPH_W, "글자 {c:?}의 한 줄 길이가 5가 아님");
            }
        }
    }

    #[test]
    fn scale_grows_with_font_size() {
        assert_eq!(scale_for(7.0), 1);
        assert_eq!(scale_for(16.0), 2); // round(16/7) = 2
        assert_eq!(scale_for(28.0), 4);
    }
}
